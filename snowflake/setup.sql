-- One-time setup. Requires ACCOUNTADMIN (or SYSADMIN + SECURITYADMIN).
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RECO_ROLE;
GRANT ROLE RECO_ROLE TO USER linhtruongsrh397;

-- Smallest warehouse; auto-suspends after 60s idle to save credits
CREATE WAREHOUSE IF NOT EXISTS RECO_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE ON WAREHOUSE RECO_WH TO ROLE RECO_ROLE;

CREATE DATABASE IF NOT EXISTS RECO;
GRANT OWNERSHIP ON DATABASE RECO TO ROLE RECO_ROLE COPY CURRENT GRANTS;

USE ROLE RECO_ROLE;
USE DATABASE RECO;
CREATE SCHEMA IF NOT EXISTS RECO.RAW;        -- raw data, loaded via COPY INTO
CREATE SCHEMA IF NOT EXISTS RECO.ANALYTICS;  -- dbt output

USE SCHEMA RECO.RAW;

CREATE FILE FORMAT IF NOT EXISTS RECO.RAW.CSV_HEADER
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS RECO.RAW.RETAILROCKET_STAGE FILE_FORMAT = RECO.RAW.CSV_HEADER;

-- Raw tables mirror the original RetailRocket CSV schemas
CREATE TABLE IF NOT EXISTS RECO.RAW.EVENTS (
  TIMESTAMP      NUMBER,      -- epoch milliseconds
  VISITORID      NUMBER,
  EVENT          VARCHAR,     -- view | addtocart | transaction
  ITEMID         NUMBER,
  TRANSACTIONID  NUMBER
);

CREATE TABLE IF NOT EXISTS RECO.RAW.ITEM_PROPERTIES (
  TIMESTAMP  NUMBER,
  ITEMID     NUMBER,
  PROPERTY   VARCHAR,
  VALUE      VARCHAR
);

CREATE TABLE IF NOT EXISTS RECO.RAW.CATEGORY_TREE (
  CATEGORYID  NUMBER,
  PARENTID    NUMBER
);
